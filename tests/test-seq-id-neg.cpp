// Verify consistent handling of negative seq_ids across all llama_memory implementations.
//
// Semantics under test [TAG_LLAMA_SEQ_ID_NEG]:
//   - seq_id < 0 : "match any sequence" wildcard in llama_memory_seq_rm() and in the
//     whole-context state APIs - ANY negative value must behave exactly like -1
//   - llama_memory_seq_cp()/seq_keep()/seq_add()/seq_div()/seq_pos_min()/seq_pos_max()
//     require a concrete sequence: any negative (or out-of-range) seq_id must be
//     rejected without touching the memory and without crashing
//   - the valid seq-id range follows the KV mapping: [0, n_seq_max), or [0, LLAMA_MAX_SEQ)
//     with --kv-unified. A seq_id above n_seq_max is then valid and every cache of the
//     memory must act on it together: seq_keep(big) drops the rest in all of them.
//     A memory cleared in one cache only is the regression this catches
//   - after every removal the memory must stay decodable (stale tails crash the next decode)
//
// Runs over the dummy models generated by test-llama-archs, so every llama_memory
// implementation (kv-cache, recurrent, hybrid, ...) is covered.

#include "arg.h"
#include "common.h"
#include "log.h"
#include "llama-cpp.h"
#include "llama.h"

#include "../src/llama-cparams.h" // LLAMA_MAX_SEQ

